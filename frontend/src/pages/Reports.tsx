import React, { useState } from 'react';
import { LuDownload } from 'react-icons/lu';
import { Plot, SERIES } from '../components/Plot';
import { Alert, Badge, Card, ErrorBox, PageHeader, Spinner, Stat, Tabs } from '../components/ui';
import { api, fileUrl, fmt } from '../lib/api';
import { useApi } from '../lib/hooks';

export default function Reports() {
  const { data: ds } = useApi<any>('/api/dataset/summary');
  const { data: mdl, error: mErr } = useApi<any>('/api/model/info');
  const [tab, setTab] = useState<'dataset' | 'model' | 'export'>('dataset');
  const [busy, setBusy] = useState<string | null>(null);
  const [err, setErr] = useState<string | null>(null);
  const exp = async (format: string, content: string) => {
    setBusy(format + content); setErr(null);
    try { await api.download('/api/reports/export', { format, content }, `dermaagents.${format}`); } catch (e: any) { setErr(e.message); } finally { setBusy(null); }
  };
  const s = ds?.summary;
  const ev = mdl?.evaluation;
  const tm = ev?.test_metrics;
  return (
    <div className="space-y-6">
      <PageHeader eyebrow="Reports" title="Reports & analytics" description="Dataset audit, classifier evaluation and exportable reports (PDF, CSV, JSON) generated from live backend data."
        actions={<Tabs tabs={[{ id: 'dataset', label: 'Dataset audit' }, { id: 'model', label: 'Model evaluation' }, { id: 'export', label: 'Export' }]} value={tab} onChange={setTab} />} />
      <ErrorBox error={err} />
      {tab === 'dataset' && (s ? (
        <div className="space-y-4">
          <div className="grid grid-cols-2 lg:grid-cols-5 gap-3">
            <Stat label="Readable images" value={fmt.int(s.total_images_readable)} />
            <Stat label="Labelled" value={fmt.int(s.labelled_images)} tone="emerald" />
            <Stat label="Unlabelled (HAM10000)" value={fmt.int(s.unlabelled_images.count)} hint="metadata CSV missing" tone="amber" />
            <Stat label="Corrupted" value={fmt.int(s.corrupted_or_non_image)} tone="rose" />
            <Stat label="Imbalance (max/min)" value={`${fmt.num(s.imbalance_ratio_max_over_min)}×`} tone="violet" />
          </div>
          <div className="grid xl:grid-cols-2 gap-4">
            <Card title="Class mapping to the proposal's six diseases">
              <table className="table-base"><thead><tr><th>Proposal class</th><th>Status</th><th>Note</th></tr></thead><tbody>
                {Object.entries<any>({ ...ds.mapping.proposal_classes, ...ds.mapping.proxy_classes }).map(([k, v]) => (
                  <tr key={k}><td className="text-ink-900">{k}</td><td><Badge tone={v.status.startsWith('supported') ? (v.status === 'supported' ? 'emerald' : 'amber') : 'rose'}>{v.status}</Badge></td><td className="text-xs text-ink-600">{v.note}</td></tr>))}
              </tbody></table>
              <div className="mt-3 text-xs text-ink-500">README classes missing from the upload: {s.readme_classes_missing_from_upload.join(', ')}.</div>
            </Card>
            <Card title="Class distribution" subtitle="Generated by the audit script"><img src={fileUrl('dataset', 'class_distribution.png')} alt="Bar chart of labelled images per class" className="rounded-xl w-full bg-white" /></Card>
            <Card title="Duplicates & leakage">
              <dl className="grid grid-cols-2 gap-y-2 text-sm">
                {Object.entries<number>(s.duplicates).map(([k, v]) => <React.Fragment key={k}><dt className="text-ink-500">{k.replace(/_/g, ' ')}</dt><dd className="text-ink-900 tabular-nums">{v}</dd></React.Fragment>)}
              </dl>
              {ds.split && <p className="text-xs text-ink-500 mt-3">Cleaning: dropped {ds.split.dropped_conflicting_label_images} images with conflicting duplicate labels and {ds.split.dropped_exact_duplicate_copies} exact duplicate copies. Grouped 70/15/15 split; near-duplicate clusters crossing splits: {ds.split.group_leakage_check}.</p>}
            </Card>
            <Card title="Image dimensions">
              <dl className="grid grid-cols-2 gap-y-2 text-sm">
                <dt className="text-ink-500">Width (median / min / max)</dt><dd>{s.dimensions.width['50%']} / {s.dimensions.width.min} / {s.dimensions.width.max}</dd>
                <dt className="text-ink-500">Height (median / min / max)</dt><dd>{s.dimensions.height['50%']} / {s.dimensions.height.min} / {s.dimensions.height.max}</dd>
                <dt className="text-ink-500">Distinct sizes</dt><dd>{s.dimensions.distinct_sizes}</dd>
                <dt className="text-ink-500">Formats</dt><dd>{Object.entries(s.file_formats).map(([k, v]) => `${k}: ${v}`).join(', ')}</dd>
              </dl>
              <div className="flex flex-wrap gap-2 mt-4">{['dataset_report.csv', 'image_dimensions_report.csv', 'corrupted_images.csv', 'duplicates_report.csv', 'dataset_summary.json', 'class_mapping.json'].map((f) => <a key={f} className="btn-ghost !py-1.5 !text-xs" href={fileUrl('dataset', f)} download><LuDownload /> {f}</a>)}</div>
            </Card>
          </div>
        </div>) : <Spinner />)}
      {tab === 'model' && (mErr ? <Alert tone="error">{mErr}</Alert> : !ev ? <Spinner /> : (
        <div className="space-y-4">
          <div className="grid grid-cols-2 lg:grid-cols-5 gap-3">
            <Stat label="Selected backbone" value={ev.selected_backbone} hint="by validation macro-F1" />
            <Stat label="Test accuracy" value={fmt.pct(tm.accuracy)} hint={`95% CI ${tm.accuracy_95ci_bootstrap.map((x: number) => fmt.pct(x, 0)).join('–')}`} tone="cyan" />
            <Stat label="Macro-F1" value={fmt.num(tm.macro_f1, 3)} hint={`balanced acc ${fmt.pct(tm.balanced_accuracy)}`} tone="violet" />
            <Stat label="Conformal coverage" value={fmt.pct(ev.conformal.test_empirical_coverage)} hint={`target ${fmt.pct(ev.conformal.target_coverage, 0)} · set size ${fmt.num(ev.conformal.test_mean_set_size, 2)}`} tone="emerald" />
            <Stat label="ECE after calibration" value={fmt.num(ev.calibration.test_ece_after, 3)} hint={`before ${fmt.num(ev.calibration.test_ece_before, 3)} · T=${fmt.num(ev.calibration.temperature, 2)}`} tone="amber" />
          </div>
          <div className="grid xl:grid-cols-2 gap-4">
            <Card title="Backbone comparison" subtitle="Same split, same head, same augmentation">
              <Plot ariaLabel="Backbone comparison" height={260}
                data={[{ type: 'bar', name: 'Validation macro-F1', x: ev.backbone_comparison.map((b: any) => b.backbone), y: ev.backbone_comparison.map((b: any) => b.val_macro_f1), marker: { color: SERIES[0] } },
                  { type: 'bar', name: 'Test macro-F1', x: ev.backbone_comparison.map((b: any) => b.backbone), y: ev.backbone_comparison.map((b: any) => b.test_macro_f1), marker: { color: SERIES[1] } },
                  { type: 'bar', name: 'Test accuracy', x: ev.backbone_comparison.map((b: any) => b.backbone), y: ev.backbone_comparison.map((b: any) => b.test_accuracy), marker: { color: SERIES[2] } }]}
                layout={{ barmode: 'group', yaxis: { range: [0, 1], tickformat: '.0%' } }} />
            </Card>
            <Card title="Out-of-distribution rejection" subtitle={`Mahalanobis threshold = ${ev.ood.percentile_of_validation}th pct of validation scores`}>
              <table className="table-base"><thead><tr><th>Probe set</th><th>n</th><th>Flagged OOD</th></tr></thead><tbody>
                <tr><td>Test split (in-distribution)</td><td>{ev.split_sizes.test}</td><td>{fmt.pct(ev.ood.test_in_distribution_false_flag_rate)}</td></tr>
                {Object.entries<any>(ev.ood.probes).map(([k, v]) => <tr key={k}><td>{k.replace(/_/g, ' ')}</td><td>{v.n}</td><td>{fmt.pct(v.flagged_ood_rate)}</td></tr>)}
              </tbody></table>
            </Card>
            <Card title="Per-class metrics (test split)">
              <div className="overflow-x-auto"><table className="table-base"><thead><tr><th>Class</th><th>Precision</th><th>Recall</th><th>F1</th><th>AUC (OvR)</th><th>n</th></tr></thead><tbody>
                {Object.entries<any>(tm.per_class).map(([c, v]) => <tr key={c}><td className={mdl.supported_classes.enabled_map[c] ? 'text-brand-600' : ''}>{c}</td><td>{fmt.num(v.precision, 2)}</td><td>{fmt.num(v.recall, 2)}</td><td>{fmt.num(v.f1, 2)}</td><td>{tm.roc_auc_ovr[c] ? fmt.num(tm.roc_auc_ovr[c], 3) : '—'}</td><td>{v.support}</td></tr>)}
              </tbody></table></div>
              <p className="text-xs text-ink-500 mt-2">{tm.roc_auc_note} Cyan rows are enabled DermaAgents classes.</p>
            </Card>
            <Card title="Confusion matrix"><img src={fileUrl('model', 'confusion_matrix.png')} alt="Confusion matrix of the selected model on the test split" className="rounded-xl w-full bg-white" /></Card>
          </div>
        </div>))}
      {tab === 'export' && (
        <div className="grid md:grid-cols-3 gap-4">
          {[['pdf', 'full', 'Full PDF report', 'Dataset audit, model evaluation, scenario comparison tables and charts.'],
            ['csv', 'scenarios', 'Scenario runs (CSV)', 'Every replication of every scenario with all metrics.'],
            ['csv', 'cases', 'Case history (CSV)', 'All stored workflow cases.'],
            ['json', 'full', 'Analytics snapshot (JSON)', 'Complete analytics payload as served to the dashboard.']].map(([f, c, t, d]) => (
            <Card key={f + c} title={t}><p className="text-sm text-ink-600 mb-4">{d}</p>
              <button className="btn-primary" disabled={!!busy} onClick={() => exp(f, c)}><LuDownload /> {busy === f + c ? 'Generating…' : `Download ${f.toUpperCase()}`}</button></Card>
          ))}
        </div>
      )}
    </div>
  );
}
